import ArgumentParser
import Foundation
import GitHooksCore

struct RepairCommand: ParsableCommand {
    static let configuration = CommandConfiguration(
        commandName: "repair",
        abstract: "Regenerate the hooks that earlier project-hooks versions installed",
        discussion: """
            Git copies hooks into each repository when it is created or cloned, so reinstalling the template does not
            update existing repositories. This command rewrites every hook that project-hooks generated and that differs
            from the current script, so that it runs this binary. Hooks from other tools stay unchanged, and running the
            command again changes nothing.

              project-hooks repair                     Repair the current repository
              project-hooks repair ~/Developer         Repair every repository under ~/Developer
              project-hooks repair --dry-run <paths>   Report what would change
            """,
    )

    @Argument(help: "Directories to search for repositories. Defaults to the current repository.")
    var paths: [String] = []

    @Option(help: "How many directory levels below each path to search.")
    var maxDepth = 4

    @Flag(help: "Report what would change without writing anything.")
    var dryRun = false

    func run() throws {
        let binaryPath = runningBinaryPath()
        let gitDirectories =
            if paths.isEmpty {
                try GitDirectoryLocator.gitDirectories(under: gitRepoRoot(), maxDepth: 0)
            } else {
                paths.flatMap { GitDirectoryLocator.gitDirectories(under: expandingTilde($0), maxDepth: maxDepth) }
            }

        printInfo("Hooks will run: \(binaryPath)")
        if binaryPath.contains("/.build/") {
            printWarn("That is a build output. Run repair again from the installed binary to point hooks at it.")
        }

        let uniqueGitDirectories = Set(gitDirectories).sorted()
        var outdated = 0
        var current = 0
        var foreign = 0
        for gitDirectory in uniqueGitDirectories {
            let hooksDir = URL(fileURLWithPath: gitDirectory).appendingPathComponent("hooks").path
            for result in try HookInstaller.repairHooks(in: hooksDir, binaryPath: binaryPath, dryRun: dryRun) {
                switch result.outcome {
                    case .missing:
                        break
                    case .current:
                        current += 1
                    case .outdated:
                        outdated += 1
                        printOK("\(dryRun ? "Would update" : "Updated") \(result.hookPath)")
                    case .foreign:
                        foreign += 1
                        printWarn("Left unchanged, not generated by project-hooks: \(result.hookPath)")
                }
            }
        }

        let verb = dryRun ? "Would update" : "Updated"
        printOK(
            "\(verb) \(outdated) hook(s) in \(uniqueGitDirectories.count) git directories; "
                + "\(current) already current; \(foreign) from other tools left unchanged.")
    }

    private func expandingTilde(_ path: String) -> String {
        (path as NSString).expandingTildeInPath
    }
}
